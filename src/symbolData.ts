/**
 * Curated categories for the symbol palette. Names are Typst symbol names
 * (checked against the compiler's `sym` module at runtime; unknown ones are
 * dropped). Keywords are German search terms.
 */
export type SymbolEntry = {
  /** Typst name, e.g. `arrow.r.double`, or a snippet for structures. */
  name: string;
  glyph: string;
  keywords?: string;
  /** Structures are inserted as snippets (with Tab stops) instead of names. */
  snippet?: string;
  label?: string;
};

export type SymbolCategory = { id: string; label: string; entries: SymbolEntry[] };

const s = (name: string, glyph: string, keywords = ""): SymbolEntry => ({ name, glyph, keywords });
const st = (label: string, glyph: string, snippet: string, keywords = ""): SymbolEntry => ({
  name: snippet.replace(/\$\{\d+:([^}]*)\}/g, "$1"),
  glyph,
  snippet,
  label,
  keywords,
});

